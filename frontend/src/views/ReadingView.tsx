import { useState } from 'react'
import type { Bundle } from '../api/types'
import './views.css'

export function ReadingView({ bundle }: { bundle: Bundle }) {
  const reading = bundle.interpretation
  const [showEvidence, setShowEvidence] = useState(false)

  if (!reading) {
    return <p className="muted">No reading was generated for this chart.</p>
  }

  return (
    <div className="stack-lg">
      <div className="between no-print">
        <div>
          <h3 className="section__title">Reading</h3>
          <p className="tiny dim" style={{ margin: 0 }}>
            Generated by the <span className="mono">{reading.engine}</span> engine
          </p>
        </div>
        <div className="cluster">
          <button
            className="btn btn--sm"
            onClick={() => setShowEvidence((v) => !v)}
            aria-pressed={showEvidence}
          >
            {showEvidence ? 'Hide' : 'Show'} calculations
          </button>
          <button className="btn btn--sm" onClick={() => window.print()}>
            Print / save PDF
          </button>
        </div>
      </div>

      <article className="reading">
        {reading.sections.map((s) => (
          <section key={s.key} className="reading__section">
            <h3 className="reading__title">{s.title}</h3>
            <div className="reading__body">
              {s.body.split('\n\n').map((para, i) => (
                <p key={i} dangerouslySetInnerHTML={{ __html: markup(para) }} />
              ))}
            </div>

            {showEvidence && s.evidence.length > 0 && (
              <div className="reading__evidence">
                <ul>
                  {s.evidence.map((e, i) => <li key={i}>{e}</li>)}
                </ul>
              </div>
            )}
          </section>
        ))}
      </article>

      <div className="notice notice--info">
        <span className="notice__mark" style={{ color: 'var(--info)' }}>i</span>
        <span>{reading.disclaimer}</span>
      </div>
    </div>
  )
}

/**
 * The rule engine emits **bold** markers and nothing else, so a full markdown
 * parser would be more surface than the job needs. Everything else is escaped
 * first, so no engine text can inject markup.
 */
function markup(text: string): string {
  const escaped = text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
  return escaped.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
}
